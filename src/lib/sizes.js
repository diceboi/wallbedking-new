/**
 * Finds factory size info by cm dimensions (width & length in cm or mm)
 */
export function findSizeByDimensions(width, length) {
  if (!width || !length) return null;
  const numW = Number(width) > 500 ? Math.round(Number(width) / 10) : Math.round(Number(width));
  const numL = Number(length) > 500 ? Math.round(Number(length) / 10) : Math.round(Number(length));
  const minDim = Math.min(numW, numL);
  const maxDim = Math.max(numW, numL);

  // Exact match
  const exact = STANDARD_BED_SIZES.find(
    (s) => s.cmWidth === minDim && s.cmLength === maxDim
  );
  if (exact) return exact;

  // Approximate match (+/- 2cm tolerance for slight manufacturing variance)
  return (
    STANDARD_BED_SIZES.find(
      (s) => Math.abs(s.cmWidth - minDim) <= 2 && Math.abs(s.cmLength - maxDim) <= 2
    ) || null
  );
}

/**
 * Finds factory size info by US inch dimensions (width & length in inches)
 */
export function findSizeByInches(widthUs, lengthUs) {
  if (!widthUs || !lengthUs) return null;
  const w = Number(widthUs);
  const l = Number(lengthUs);
  const minDim = Math.min(w, l);
  const maxDim = Math.max(w, l);

  return (
    STANDARD_BED_SIZES.find(
      (s) => s.widthUs === minDim && s.lengthUs === maxDim
    ) || null
  );
}

/**
 * Finds factory size info by dimension key (e.g. "120x200" or "200x120" or "48x80")
 */
export function findSizeByKey(key) {
  if (!key) return null;
  const m = String(key).match(/(\d+)\s*[xX×]\s*(\d+)/);
  if (!m) return null;
  const dim1 = Number(m[1]);
  const dim2 = Number(m[2]);

  // If dimensions look like cm or mm
  if (dim1 > 50 || dim2 > 50) {
    return findSizeByDimensions(dim1, dim2);
  }
  // If dimensions look like inches (e.g. 48x80)
  return findSizeByInches(dim1, dim2);
}

/**
 * Finds factory size info from a product object or label
 */
export function resolveFactorySize(itemOrLabel) {
  if (!itemOrLabel) return null;

  if (typeof itemOrLabel === "object") {
    // If this is a flagship product or multi-size summary, it has no single factory size
    if (itemOrLabel.sizeLabel && (/Available|Modular|Sizes/i.test(itemOrLabel.sizeLabel) || /(\d+)\s*[xX×]\s*(\d+)\s*[-–—]\s*(\d+)\s*[xX×]\s*(\d+)/i.test(itemOrLabel.sizeLabel))) {
      return null;
    }

    // 1. Try width_us and length_us
    if (itemOrLabel.width_us && itemOrLabel.length_us) {
      const match = findSizeByInches(itemOrLabel.width_us, itemOrLabel.length_us);
      if (match) return match;
    }
    // 2. Try width and length in mm
    if (itemOrLabel.width && itemOrLabel.length) {
      const match = findSizeByDimensions(itemOrLabel.width, itemOrLabel.length);
      if (match) return match;
    }
    // 3. Try sizeSlug
    if (itemOrLabel.sizeSlug) {
      const match = findSizeByKey(itemOrLabel.sizeSlug);
      if (match) return match;
    }
    // 4. Try label, name, or name_us
    const textToSearch = `${itemOrLabel.size_us || ""} ${itemOrLabel.name || ""} ${itemOrLabel.name_us || ""} ${itemOrLabel.slug || ""}`;
    const mInch = textToSearch.match(/(\d{2})\s*"\s*[xX×]\s*(\d{2})\s*"/);
    if (mInch) {
      const match = findSizeByInches(mInch[1], mInch[2]);
      if (match) return match;
    }
    const m = textToSearch.match(/(\d{2,3})\s*[xX×]\s*(\d{2,3})/);
    if (m) {
      const match = findSizeByKey(`${m[1]}x${m[2]}`);
      if (match) return match;
    }
  } else if (typeof itemOrLabel === "string") {
    // If string is a multi-size range, do not resolve as a single size
    if (/(\d+)\s*[xX×]\s*(\d+)\s*[-–—]\s*(\d+)\s*[xX×]\s*(\d+)/i.test(itemOrLabel) || /Available|Modular|Sizes/i.test(itemOrLabel)) {
      return null;
    }

    const mInch = itemOrLabel.match(/(\d{2})\s*"\s*[xX×]\s*(\d{2})\s*"/);
    if (mInch) {
      const match = findSizeByInches(mInch[1], mInch[2]);
      if (match) return match;
    }

    const m = itemOrLabel.match(/(\d{2,3})\s*[xX×]\s*(\d{2,3})/);
    if (m) {
      const match = findSizeByKey(`${m[1]}x${m[2]}`);
      if (match) return match;
    }

    // Check by standard name keywords
    const lower = itemOrLabel.toLowerCase();
    if (lower.includes("super king xl") || lower.includes("192x200") || lower.includes("76\" x 80\"")) return findSizeByKey("192x200");
    if (lower.includes("super king xxl") || lower.includes("200x200") || lower.includes("79\" x 79\"")) return findSizeByKey("200x200");
    if (lower.includes("super king") || lower.includes("180x200") || lower.includes("71\" x 80\"")) return findSizeByKey("180x200");
    if (lower.includes("european king") || lower.includes("160x200") || lower.includes("63\" x 80\"")) return findSizeByKey("160x200");
    if (lower.includes("european double long") || lower.includes("140x200")) return findSizeByKey("140x200");
    if (lower.includes("european double") || lower.includes("140x190") || lower.includes("55\" x 75\"")) return findSizeByKey("140x190");
    if (lower.includes("european small double") || lower.includes("120x200") || lower.includes("48\" x 80\"")) return findSizeByKey("120x200");
    if (lower.includes("small double") || lower.includes("120x190") || lower.includes("48\" x 75\"")) return findSizeByKey("120x190");
    if (lower.includes("three quarter")) return findSizeByKey("120x190");
    if (lower.includes("double") || lower.includes("135x190") || lower.includes("54\" x 75\"")) return findSizeByKey("135x190");
    if (lower.includes("queen") || lower.includes("150x200") || lower.includes("60\" x 80\"")) return findSizeByKey("150x200");
    if (lower.includes("twin xl") || lower.includes("96x200") || lower.includes("38\" x 80\"")) return findSizeByKey("96x200");
    if (lower.includes("twin") || lower.includes("96x190") || lower.includes("38\" x 75\"")) return findSizeByKey("96x190");
    if (lower.includes("european single xl long") || lower.includes("96x200")) return findSizeByKey("96x200");
    if (lower.includes("european single xl") || lower.includes("96x190")) return findSizeByKey("96x190");
    if (lower.includes("european single") || lower.includes("90x200") || lower.includes("36\" x 80\"")) return findSizeByKey("90x200");
    if (lower.includes("small single xl long") || lower.includes("80x200") || lower.includes("31\" x 80\"")) return findSizeByKey("80x200");
    if (lower.includes("small single xl") || lower.includes("80x190") || lower.includes("31\" x 75\"")) return findSizeByKey("80x190");
    if (lower.includes("small single") || lower.includes("76x190") || lower.includes("30\" x 75\"")) return findSizeByKey("76x190");
    if (lower.includes("single") || lower.includes("90x190") || lower.includes("36\" x 75\"")) return findSizeByKey("90x190");
  }

  return null;
}

/**
 * Formats size label for a specific storefront market (US Imperial vs EU Metric)
 */
export function getLocalizedSizeLabel(itemOrLabel, locale = "en") {
  const normLocale = (locale || "en").toLowerCase();
  const factory = resolveFactorySize(itemOrLabel);

  if (normLocale === "us") {
    if (factory) {
      return factory.usLabel;
    }
  } else {
    if (factory) {
      return factory.euLabel;
    }
  }

  return typeof itemOrLabel === "string" ? itemOrLabel : (itemOrLabel?.sizeLabel || itemOrLabel?.size || "");
}
